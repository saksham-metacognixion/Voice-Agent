export type DiffOp = { kind: 'same' | 'add' | 'del'; text: string };

/**
 * A line diff for the Versions tab's Compare — the smallest thing that shows what a
 * feedback patch or a manual edit changed. Longest-common-subsequence on lines; the
 * prompts are a few hundred lines, so the quadratic table is nothing.
 */
export function lineDiff(before: string, after: string): DiffOp[] {
  const a = before.split(/\r?\n/);
  const b = after.split(/\r?\n/);
  const n = a.length;
  const m = b.length;
  const table: Uint32Array[] = Array.from({ length: n + 1 }, () => new Uint32Array(m + 1));
  for (let i = n - 1; i >= 0; i -= 1) {
    for (let j = m - 1; j >= 0; j -= 1) {
      table[i]![j] = a[i] === b[j] ? table[i + 1]![j + 1]! + 1 : Math.max(table[i + 1]![j]!, table[i]![j + 1]!);
    }
  }
  const out: DiffOp[] = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (a[i] === b[j]) {
      out.push({ kind: 'same', text: a[i]! });
      i += 1;
      j += 1;
    } else if (table[i + 1]![j]! >= table[i]![j + 1]!) {
      out.push({ kind: 'del', text: a[i]! });
      i += 1;
    } else {
      out.push({ kind: 'add', text: b[j]! });
      j += 1;
    }
  }
  while (i < n) out.push({ kind: 'del', text: a[i++]! });
  while (j < m) out.push({ kind: 'add', text: b[j++]! });
  return out;
}

export function diffCounts(ops: DiffOp[]): { added: number; removed: number } {
  return { added: ops.filter((o) => o.kind === 'add').length, removed: ops.filter((o) => o.kind === 'del').length };
}
