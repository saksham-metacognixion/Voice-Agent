/**
 * Records W3's "Hear this voice" clip for every catalogue voice, on our own voice stack,
 * so the picker plays something under `VOICE_VENDOR_SAMPLES=deny` — the vendor's own
 * preview clips say its name aloud (ADR 0020 §5), and without a clip of ours the play
 * button is disabled on every voice.
 *
 *   pnpm --filter @portal/api samples:voices                   # every voice without a clip
 *   pnpm --filter @portal/api samples:voices --concurrency=4   # four calls at a time
 *   pnpm --filter @portal/api samples:voices --force 11labs-Adrian cartesia-Allie
 *
 * Per voice: one neutral line in the voice's native language (no business name, no
 * vendor name) through `sample-recorder.ts` → `frontend/web/public/samples/voices/<hash>.mp3`,
 * and the voice id → file entry in `src/modules/voices/voice-samples.generated.ts`, which
 * is rewritten after every clip so an interrupted run keeps what it made. Rerunning skips
 * voices that already have a file. The voice list is the local `voices` cache — the same
 * public catalogue every environment's platform workspace lists; `custom_voice_*` ids are
 * account-specific and skipped. Costs a few cents of call time per clip.
 */
import 'reflect-metadata';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { adminDb } from '@portal/db';
import { retellLanguage } from '@portal/schemas';
import { agentStackTiers, voiceModelFor, type Language } from '../src/modules/retell/retell.types';
import { RetellConfig } from '../src/modules/retell/retell.config';
import { RetellGateway } from '../src/modules/retell/retell.gateway';
import { nativeLanguages } from '../src/modules/voices/voice-languages';
import { VOICE_SAMPLE_FILES } from '../src/modules/voices/voice-samples.generated';
import { voiceSampleFile } from '../src/modules/voices/voice-samples';
import { ROOT, startRecorder } from './sample-recorder';

const OUT_DIR = path.join(ROOT, 'frontend/web/public/samples/voices');
const MANIFEST = path.join(ROOT, 'backend/api/src/modules/voices/voice-samples.generated.ts');

/** One line per base language, with the locale the agent runs in when the accent has none of its own. */
const LINES: Record<string, { locale: Language; text: string }> = {
  en: {
    locale: 'en-US',
    text: 'Hi there, thanks for calling. I can book an appointment, answer your questions, or take a message for the team. How can I help you today?',
  },
  es: {
    locale: 'es-419',
    text: 'Hola, gracias por llamar. Puedo agendar una cita, responder sus preguntas o tomar un mensaje para el equipo. ¿En qué le puedo ayudar hoy?',
  },
  fr: {
    locale: 'fr-FR',
    text: "Bonjour, merci de votre appel. Je peux prendre un rendez-vous, répondre à vos questions ou prendre un message pour l'équipe. Comment puis-je vous aider aujourd'hui ?",
  },
  de: {
    locale: 'de-DE',
    text: 'Hallo, vielen Dank für Ihren Anruf. Ich kann einen Termin vereinbaren, Ihre Fragen beantworten oder eine Nachricht für das Team aufnehmen. Wie kann ich Ihnen heute helfen?',
  },
  pt: {
    locale: 'pt-BR',
    text: 'Olá, obrigado por ligar. Posso marcar um horário, responder às suas perguntas ou anotar um recado para a equipe. Como posso ajudar você hoje?',
  },
  zh: {
    locale: 'zh-CN',
    text: '您好，感谢您的来电。我可以帮您预约、回答您的问题，或者为团队留言。请问今天有什么可以帮您？',
  },
  ja: {
    locale: 'ja-JP',
    text: 'お電話ありがとうございます。ご予約の受付、ご質問へのお答え、チームへのご伝言を承ります。本日はどのようなご用件でしょうか？',
  },
};

function lineFor(voice: { languages: string[]; accent: string | null }): {
  locale: Language;
  text: string;
} {
  const native = nativeLanguages(voice);
  for (const locale of native) {
    const line = LINES[locale.toLowerCase().split('-')[0] ?? ''];
    if (!line) continue;
    const exact = retellLanguage.safeParse(locale);
    return { text: line.text, locale: exact.success ? (exact.data as Language) : line.locale };
  }
  // An accent we cannot place, or a native language we have no line for: English.
  return LINES.en!;
}

function writeManifest(files: Record<string, string>) {
  const entries = Object.keys(files)
    .sort()
    .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(files[id])},`)
    .join('\n');
  writeFileSync(
    MANIFEST,
    `// Generated by \`pnpm --filter @portal/api samples:voices\` — do not edit by hand.
// voice id → clip under frontend/web/public/samples/voices/ (see voice-samples.ts).
export const VOICE_SAMPLE_FILES: Readonly<Record<string, string>> = {${entries ? `\n${entries}\n` : ''}};
`,
  );
}

async function main() {
  const args = process.argv.slice(2);
  const force = args.includes('--force');
  const concurrency = Math.max(
    1,
    Number(args.find((a) => a.startsWith('--concurrency='))?.split('=')[1] ?? 3),
  );
  const only = args.filter((a) => !a.startsWith('-'));

  const gw = new RetellGateway(new RetellConfig());
  gw.config.assertConfigured();
  const row = await adminDb.agentStackConfig.findFirst({ orderBy: { version: 'desc' } });
  if (!row) throw new Error('agent_stack_configs is empty — run pnpm db:seed');
  const tiers = agentStackTiers.parse(row.tiersJson);

  const voices = await adminDb.voice.findMany({ orderBy: { retellVoiceId: 'asc' } });
  if (!voices.length)
    throw new Error(
      'the voices cache is empty — start the worker once (voice-cache) or GET /voices',
    );
  for (const id of only)
    if (!voices.some((v) => v.retellVoiceId === id))
      throw new Error(`no voice "${id}" in the cache`);

  mkdirSync(OUT_DIR, { recursive: true });
  const files: Record<string, string> = { ...VOICE_SAMPLE_FILES };
  const todo = voices.filter((v) => {
    if (only.length) return only.includes(v.retellVoiceId);
    if (v.retellVoiceId.startsWith('custom_voice_')) return false;
    const file = files[v.retellVoiceId];
    return force || !file || !existsSync(path.join(OUT_DIR, file));
  });
  console.log(`${todo.length} of ${voices.length} voices to record, ${concurrency} at a time`);

  const recorder = await startRecorder(gw, { browsers: Math.min(concurrency, todo.length || 1) });
  const failed: string[] = [];
  let next = 0;
  let done = 0;
  try {
    await Promise.all(
      recorder.browsers.map(async (browser) => {
        while (next < todo.length) {
          const voice = todo[next++]!;
          const id = voice.retellVoiceId;
          const stack = tiers[voice.tier];
          const line = lineFor(voice);
          const file = voiceSampleFile(id);
          try {
            const { callId, seconds } = await recorder.record(
              browser,
              {
                name: `dev-sample-voice-${file.slice(0, 8)}`,
                text: line.text,
                voiceId: id,
                voiceModel: voiceModelFor(voice.provider, stack.voice_model),
                language: line.locale,
                stack,
                metadata: { purpose: 'voice_sample', voice_id: id },
                bitrate: '64k',
              },
              path.join(OUT_DIR, file),
            );
            files[id] = file;
            writeManifest(files);
            console.log(
              `[${++done}/${todo.length}] ${id} (${line.locale}) call ${callId} → ${file} (${seconds.toFixed(1)} s)`,
            );
          } catch (error) {
            failed.push(id);
            console.error(
              `[${++done}/${todo.length}] ${id} FAILED:`,
              error instanceof Error ? error.message : error,
            );
          }
        }
      }),
    );
  } finally {
    const logs = recorder.browsers.flatMap((b) => b.logs);
    if (logs.length) console.log('\nbrowser:', logs.slice(-10).join('\n'));
    recorder.close();
    await adminDb.$disconnect();
  }
  if (failed.length) {
    console.error(
      `\nfailed (${failed.length}): ${failed.join(' ')}\nrerun to retry them — made clips are kept.`,
    );
    process.exit(1);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
